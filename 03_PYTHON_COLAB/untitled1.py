import pandas as pd
import numpy as np

# Commodity columns
commodities = [
    "Soybeans",
    "Maize",
    "Rice_Thai_5pct",
    "Wheat_US_HRW"
]

# Recreate monthly percentage changes
monthly_changes = clean_data[
    ["Date"] + commodities
].copy()

for col in commodities:
    monthly_changes[col + "_MoM_Pct"] = (
        clean_data[col].pct_change(fill_method=None) * 100
    )

    monthly_changes[col + "_YoY_Pct"] = (
        clean_data[col].pct_change(periods=12, fill_method=None) * 100
    )

# Recreate monthly returns correlation
monthly_returns = clean_data[commodities].pct_change(
    fill_method=None
).dropna()

return_correlation = monthly_returns.corr()

# Recreate latest price index comparison
price_index = clean_data[["Date"] + commodities].copy()

for col in commodities:
    price_index[col] = (
        clean_data[col] / clean_data[col].iloc[0]
    ) * 100

latest_index = price_index.iloc[-1]

index_comparison = pd.DataFrame({
    "Commodity": commodities,
    "January_2021_Index": [100] * len(commodities),
    "October_2026_Index": [
        latest_index[col] for col in commodities
    ],
    "Total_Change_Pct": [
        latest_index[col] - 100 for col in commodities
    ]
})

display(return_correlation.round(3))
display(index_comparison.round(2))

output_file = "CFCO_Day3_Statistical_Analysis.xlsx"

with pd.ExcelWriter(output_file, engine="openpyxl") as writer:

    monthly_changes.to_excel(
        writer, sheet_name="Monthly_Changes", index=False
    )

    price_index.to_excel(
        writer, sheet_name="Price_Index", index=False
    )

    return_correlation.to_excel(
        writer, sheet_name="Monthly_Return_Correlation"
    )

    index_comparison.to_excel(
        writer, sheet_name="Latest_Index_Comparison", index=False
    )

