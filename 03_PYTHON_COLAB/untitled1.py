# DAY 2 - INITIAL DATA EXTRACTION

import pandas as pd
import numpy as np

file_path = "CMO-Historical-Data-Monthly.xlsx"

raw = pd.read_excel(
    file_path,
    sheet_name="Monthly Prices",
    header=None
)

print("Original dataset shape:", raw.shape)

# Identify the actual headers and units
commodity_headers = raw.iloc[4].tolist()
commodity_units = raw.iloc[5].tolist()

print("\nCommodity column information:")

for i, name in enumerate(commodity_headers):
    if name in [
        "Soybeans",
        "Maize",
        "Rice, Thai 5% ",
        "Wheat, US HRW"
    ]:
        print(name, "-", commodity_units[i])

# Extract only our four selected commodity series

selected_columns = {
    "Soybeans": 24,
    "Maize": 30,
    "Rice_Thai_5pct": 32,
    "Wheat_US_HRW": 37
}

# Monthly data starts at row 6
data = raw.iloc[6:, [0] + list(selected_columns.values())].copy()

data.columns = ["Period"] + list(selected_columns.keys())

print("Extracted dataset:")
display(data.head())

print("\nLast five records:")
display(data.tail())

# Convert the original period format into dates
# Example: 2026M10 becomes 2026-10-01

data["Date"] = pd.to_datetime(
    data["Period"].astype(str).str.replace("M", "-", regex=False)
    + "-01",
    format="%Y-%m-%d",
    errors="coerce"
)

# Select the project analysis period
analysis_data = data[
    (data["Date"] >= "2021-01-01") &
    (data["Date"] <= "2026-10-01")
].copy()

print("Analysis period:")
print(analysis_data["Date"].min())
print(analysis_data["Date"].max())

print("Number of monthly records:", len(analysis_data))

# DATA TYPE CONVERSION

# Work on a separate copy
clean_data = analysis_data.copy()

# Convert commodity prices into numeric values
commodity_columns = [
    "Soybeans",
    "Maize",
    "Rice_Thai_5pct",
    "Wheat_US_HRW"
]

for col in commodity_columns:
    clean_data[col] = pd.to_numeric(
        clean_data[col],
        errors="coerce"
    )

print("DATA TYPES AFTER CONVERSION")
print(clean_data.dtypes)

display(clean_data.head())

# MISSING VALUE ANALYSIS

missing_report = pd.DataFrame({
    "Column": clean_data.columns,
    "Missing_Count": clean_data.isnull().sum().values,
    "Missing_Percentage": (
        clean_data.isnull().mean().values * 100
    )
})

display(missing_report)

print("\nTotal missing values:")
print(clean_data.isnull().sum().sum())

# DUPLICATE DATE CHECK

duplicate_count = clean_data["Date"].duplicated().sum()

print("Duplicate dates:", duplicate_count)

duplicate_records = clean_data[
    clean_data["Date"].duplicated(keep=False)
]

display(duplicate_records)

# PRICE VALIDATION

for col in commodity_columns:

    print("\nCommodity:", col)

    print("Minimum:", clean_data[col].min())
    print("Maximum:", clean_data[col].max())
    print("Average:", clean_data[col].mean())

    invalid_prices = clean_data[
        clean_data[col] <= 0
    ]

    print("Non-positive prices:", len(invalid_prices))

# FINAL DATA QUALITY SUMMARY

quality_summary = pd.DataFrame({
    "Test": [
        "Total Records",
        "Duplicate Dates",
        "Missing Values",
        "Invalid Dates",
        "Negative or Zero Prices"
    ],

    "Result": [
        len(clean_data),
        clean_data["Date"].duplicated().sum(),
        clean_data.isnull().sum().sum(),
        clean_data["Date"].isnull().sum(),
        sum(
            (clean_data[c] <= 0).sum()
            for c in commodity_columns
        )
    ]
})

display(quality_summary)

# EXPORT VALIDATED DATASET

# Preserve only validated records
final_data = clean_data.dropna(
    subset=["Date"] + commodity_columns
).copy()

# Sort chronologically
final_data = final_data.sort_values("Date")

# Keep one observation per month only if unique
assert not final_data["Date"].duplicated().any()

# Check the expected analysis period
assert len(final_data) == 70
assert final_data["Date"].min() == pd.Timestamp("2021-01-01")
assert final_data["Date"].max() == pd.Timestamp("2026-10-01")

# Export CSV
final_data.to_csv(
    "CFCO_Cleaned_Commodity_Prices.csv",
    index=False
)

# Export Excel
with pd.ExcelWriter(
    "CFCO_Cleaned_Commodity_Prices.xlsx"
) as writer:

    final_data.to_excel(
        writer,
        sheet_name="Cleaned_Data",
        index=False
    )

    quality_summary.to_excel(
        writer,
        sheet_name="Quality_Report",
        index=False
    )

print("Validated dataset exported successfully!")
print("Final records:", len(final_data))

